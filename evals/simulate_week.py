"""Run the analyst's statistics on a simulated week. No API key needed.

    uv run python evals/simulate_week.py

The data is generated by growthcrew.analytics.simulate, where the outcome angle is set to
win on LinkedIn and in the ad test, and the landing page test is too small to call.
"""

from sqlmodel import SQLModel, create_engine

from growthcrew.analytics.analysis import analyze
from growthcrew.analytics.ingest import ingest
from growthcrew.analytics.simulate import seed
from growthcrew.db import models  # noqa: F401


def main() -> None:
    engine = create_engine("sqlite://")
    SQLModel.metadata.create_all(engine)
    for source, text in seed(engine).items():
        result = ingest(engine, "acme", source, text)
        note = f", unmatched: {', '.join(result.unmatched_refs)}" if result.unmatched_refs else ""
        print(f"ingested {source}: {result.matched} of {result.rows} rows matched{note}")

    analysis = analyze(engine, "acme")
    print(f"\nWindow {analysis.window_start} to {analysis.window_end}")
    print("\nPerformance by angle")
    for row in analysis.performance:
        if row.dimension == "angle":
            print(f"  {row.id:>3} {row.value:<13} {row.metric:<19} "
                  f"{row.successes:>4}/{row.trials:<6} = {row.rate_pct}%")  # fmt: skip
    print("\nExperiment readouts")
    for r in analysis.readouts:
        arms = ", ".join(f"{a['label']} {a['successes']}/{a['trials']} ({a['rate_pct']}%)"
                         for a in r.arms)  # fmt: skip
        print(f"  {r.id} [{r.kind}] {r.name}\n     {arms}")
        if r.status == "significant":
            print(f"     -> SIGNIFICANT: {r.winner} wins, +{r.lift_pct}% over runner-up, "
                  f"adjusted p={r.p_value}")  # fmt: skip
        else:
            print(f"     -> {r.status.upper()}: {r.note}")
    print("\nAnomalies")
    for a in analysis.anomalies:
        print(f"  {a.id} {a.series} on {a.date}: {a.value:.0f} vs typical {a.typical:.0f} "
              f"({a.change_pct:+}% {a.direction})")  # fmt: skip


if __name__ == "__main__":
    main()
